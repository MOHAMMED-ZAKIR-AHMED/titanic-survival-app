# Logistic regression is a classification model which comes under supervised learning

# import the libraries
import pandas as pd
import numpy as np
import seaborn as sns

from matplotlib import pyplot as plt

sns.get_dataset_names()

# Loading the data set
df = sns.load_dataset('titanic')

df.head(3)  #sibsp - siblings / spouse

# All columns
df.columns

# we use drop function to remove the unwanted columns names for training the data
df.drop(columns = ['sibsp','parch','class','who','adult_male','embark_town','alive','alone','deck'],inplace=True)

df.columns

df.drop(columns = ['embarked'], inplace=True)

df.columns

df.head(3)

# Checking the null values if exists
df.isnull().sum()

df.shape

# Let's fill the missing values for age and embark_town
sns.boxplot(df['age'])

df.info()

df['age'].median()

df['age'] = df['age'].fillna(df['age'].median())

df.isnull().sum()

df

df.head()

# this dummies function is to replace the values of categorical data in different parts
df = pd.get_dummies(df,columns=['sex'], drop_first = True, dtype = "int64")

df.head() # 1 -> Male ; 0 -> Female

df.info()

# Now we need to separate X and Y columns
X = df.drop(columns = ["survived"])  # Independent Var
y = df['survived'] # dependent var

df.info()

X.head(3)

y.head(3)

# Split the data into 80 and 20
from sklearn.model_selection import train_test_split

X_train, X_test, y_train, y_test = train_test_split(X,y,test_size=0.2,random_state=0)

#Model Training

from sklearn.linear_model import LogisticRegression

#logistic regression
model = LogisticRegression()

model.fit(X_train,y_train)

# Testing
ypred = model.predict(X_test)

ypred

# We call metrics like accuracy
from sklearn.metrics import accuracy_score

#Performance
logistic_score = accuracy_score(ypred,y_test)

logistic_score

# Evaluation Metrics
from sklearn.metrics import confusion_matrix, accuracy_score, precision_score,recall_score,f1_score

print(confusion_matrix(ypred,y_test))
print(accuracy_score(ypred,y_test))
print(precision_score(ypred,y_test))
print(recall_score(ypred,y_test))
print(f1_score(ypred,y_test))

# Independent Variable Columns
